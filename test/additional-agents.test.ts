import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { tmpDir } from "./helpers.js";
import { skillTargets, syncSkills, uninstallSkills } from "../src/skills-sync.js";
import { syncAgentConfig, uninstallAgentConfig, BLOCK_START } from "../src/agent-config.js";
import { parse } from "yaml";
import { additionalAgentConfigStatus } from "../src/agent-integrations.js";

let home: string;
let kb: string;
function write(file: string, content: string) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}
function installed() {
  write(path.join(home, ".cursor/cli-config.json"), "{}\n");
  write(path.join(home, ".hermes/config.yaml"), "model: test\n");
}
function source(content = "Run team workflow") {
  write(path.join(kb, "skills/deploy/SKILL.md"), `---\nname: deploy\ndescription: Deploy the team project\n---\n${content}\n`);
}
beforeEach(() => {
  home = tmpDir("extra agents ' $ home");
  kb = path.join(home, "org-kb");
  write(path.join(kb, "team.md"), "Team facts\n");
  vi.stubEnv("HERMES_HOME", "");
});
afterEach(() => {
  vi.unstubAllEnvs();
  fs.rmSync(home, { recursive: true, force: true });
});

describe("Cursor / Hermes skills", () => {
  it("does not count a Hermes config created only for knowbase as installation evidence", () => {
    const envFile = path.join(home, ".hermes/.env");
    write(envFile, "# existing Hermes installation\n");
    syncAgentConfig(kb, home);
    expect(fs.existsSync(path.join(home, ".hermes/config.yaml"))).toBe(true);
    fs.rmSync(envFile);
    expect(skillTargets(home).map(t => t.name)).toEqual(["Claude Code"]);
    uninstallAgentConfig(home);
    expect(fs.existsSync(path.join(home, ".hermes/config.yaml"))).toBe(false);
  });

  it("recognizes and preserves user changes to a Hermes config initially generated by knowbase", () => {
    const envFile = path.join(home, ".hermes/.env");
    write(envFile, "# Hermes\n");
    syncAgentConfig(kb, home);
    fs.rmSync(envFile);
    fs.appendFileSync(path.join(home, ".hermes/config.yaml"), "model: my-model\n");
    expect(skillTargets(home).map(t => t.name)).toContain("Hermes");
    uninstallAgentConfig(home);
    expect(parse(fs.readFileSync(path.join(home, ".hermes/config.yaml"), "utf8")).model).toBe("my-model");
  });

  it("uninstalled agents and managed artifacts alone do not count as installations", () => {
    write(path.join(home, ".cursor/knowbase/context.md"), "managed");
    write(path.join(home, ".hermes/plugins/knowbase-context/context.md"), "managed");
    fs.mkdirSync(path.join(home, ".cursor/skills"), { recursive: true });
    fs.mkdirSync(path.join(home, ".hermes/skills"), { recursive: true });
    expect(skillTargets(home).map(t => t.name)).toEqual(["Claude Code"]);
  });

  it("distributes, repairs, propagates updates/deletions and preserves foreign skills", () => {
    installed();
    source();
    const changes = syncSkills(kb, home);
    expect(changes.map(c => [c.tool, c.action])).toEqual([
      ["Claude Code", "created"], ["Cursor", "created"], ["Hermes", "created"],
    ]);
    for (const folder of [".cursor", ".hermes"]) {
      const file = path.join(home, folder, "skills/org-deploy/SKILL.md");
      expect(fs.readFileSync(file, "utf8")).toContain("name: org-deploy");
      write(file, "tampered");
    }
    expect(syncSkills(kb, home).filter(c => c.action === "updated").map(c => c.tool)).toEqual(["Cursor", "Hermes"]);
    source("Updated workflow");
    syncSkills(kb, home);
    expect(fs.readFileSync(path.join(home, ".hermes/skills/org-deploy/SKILL.md"), "utf8")).toContain("Updated workflow");
    write(path.join(home, ".cursor/skills/org-personal/SKILL.md"), "personal");
    fs.rmSync(path.join(kb, "skills/deploy"), { recursive: true });
    expect(syncSkills(kb, home).filter(c => c.action === "removed").map(c => c.tool)).toEqual(["Claude Code", "Cursor", "Hermes"]);
    expect(fs.existsSync(path.join(home, ".cursor/skills/org-personal/SKILL.md"))).toBe(true);
  });

  it("resolves custom HERMES_HOME consistently and cleans up even if install markers are gone", () => {
    const custom = path.join(home, "custom hermes");
    vi.stubEnv("HERMES_HOME", custom);
    write(path.join(custom, "config.yaml"), "model: test\n");
    source();
    syncSkills(kb, home);
    expect(fs.existsSync(path.join(custom, "skills/org-deploy/SKILL.md"))).toBe(true);
    expect(fs.existsSync(path.join(home, ".hermes"))).toBe(false);
    fs.rmSync(path.join(custom, "config.yaml"));
    expect(uninstallSkills(home).some(r => r.tool === "Hermes" && r.removed)).toBe(true);
    expect(fs.existsSync(path.join(custom, "skills/org-deploy"))).toBe(false);
  });
});

describe("Cursor / Hermes context lifecycle", () => {
  it("excludes repository skills from every client prompt while continuing skill distribution", () => {
    installed();
    source();
    // Seed an older directory tree, then exercise the daemon's replacement path.
    const initial = syncAgentConfig(kb, home);
    const cursorRule = path.join(home, ".cursor/knowbase/plugin/rules/knowbase.mdc");
    for (const file of [...initial.map(c => c.file), cursorRule]) {
      const prompt = fs.readFileSync(file, "utf8");
      fs.writeFileSync(file, prompt.replace("team.md", "skills/\n  old-team-skill/\n    SKILL.md\nteam.md"));
    }
    const changes = syncAgentConfig(kb, home, { onlyExisting: true });
    expect(changes.map(c => c.name)).toEqual(["Claude Code", "Codex", "Cursor", "Hermes"]);
    for (const c of changes) {
      const prompt = fs.readFileSync(c.file, "utf8");
      expect(prompt).toContain("team.md");
      expect(prompt).not.toMatch(/^skills\/$/m);
      expect(prompt).not.toContain("SKILL.md");
      expect(prompt).not.toContain("deploy/");
    }
    const rule = fs.readFileSync(path.join(home, ".cursor/knowbase/plugin/rules/knowbase.mdc"), "utf8");
    expect(rule).not.toMatch(/^skills\/$/m);
    expect(rule).not.toContain("SKILL.md");
    syncSkills(kb, home);
    for (const folder of [".claude", ".cursor", ".hermes"]) {
      expect(fs.readFileSync(path.join(home, folder, "skills/org-deploy/SKILL.md"), "utf8")).toContain("Run team workflow");
    }
  });

  it("executes Cursor workspaceOpen hook, loads an always-on plugin rule and preserves other hooks", () => {
    installed();
    const hooksFile = path.join(home, ".cursor/hooks.json");
    write(hooksFile, JSON.stringify({ version: 1, extra: true, hooks: { workspaceOpen: [{ command: "echo personal" }], stop: [{ command: "echo done" }] } }));
    const changes = syncAgentConfig(kb, home);
    expect(changes.find(c => c.name === "Cursor")?.action).toBe("created");
    const hooks = JSON.parse(fs.readFileSync(hooksFile, "utf8"));
    expect(hooks.extra).toBe(true);
    expect(hooks.hooks.workspaceOpen[0]).toEqual({ command: "echo personal" });
    const hook = hooks.hooks.workspaceOpen[1];
    const output = JSON.parse(execFileSync(hook.command, { shell: true, input: "{}", encoding: "utf8" }));
    const plugin = output.pluginPaths[0];
    expect(JSON.parse(fs.readFileSync(path.join(plugin, ".cursor-plugin/plugin.json"), "utf8")).name).toBe("knowbase-context");
    const rule = fs.readFileSync(path.join(plugin, "rules/knowbase.mdc"), "utf8");
    expect(rule).toMatch(/^---\nalwaysApply: true\n---\n/);
    expect(rule).toContain(kb);
    expect(rule).toContain("team.md");
    expect(syncAgentConfig(kb, home).every(c => c.action === "unchanged")).toBe(true);
    write(path.join(kb, "new.md"), "New facts");
    syncAgentConfig(kb, home, { onlyExisting: true });
    expect(fs.readFileSync(path.join(plugin, "rules/knowbase.mdc"), "utf8")).toContain("new.md");
    uninstallAgentConfig(home);
    expect(JSON.parse(fs.readFileSync(hooksFile, "utf8"))).toEqual({ version: 1, extra: true, hooks: { workspaceOpen: [{ command: "echo personal" }], stop: [{ command: "echo done" }] } });
    expect(fs.existsSync(plugin)).toBe(false);
  });

  it("enables Hermes prompt plugin without changing personality, YAML comments or unrelated settings", () => {
    installed();
    const file = path.join(home, ".hermes/config.yaml");
    write(file, "# Keep my settings\nmodel: test\nplugins:\n  enabled: [personal]\n  disabled: [other]\n");
    write(path.join(home, ".hermes/SOUL.md"), "My persona\n");
    const changes = syncAgentConfig(kb, home);
    const hermes = changes.find(c => c.name === "Hermes");
    expect(hermes?.action).toBe("created");
    const config = fs.readFileSync(file, "utf8");
    expect(config).toContain("# Keep my settings");
    expect(parse(config)).toEqual({ model: "test", plugins: { enabled: ["personal", "knowbase-context"], disabled: ["other"] } });
    expect(fs.readFileSync(hermes!.file, "utf8")).toContain(kb);
    expect(fs.readFileSync(path.join(home, ".hermes/SOUL.md"), "utf8")).toBe("My persona\n");
    uninstallAgentConfig(home);
    expect(parse(fs.readFileSync(file, "utf8"))).toEqual({ model: "test", plugins: { enabled: ["personal"], disabled: ["other"] } });
    expect(fs.readFileSync(file, "utf8")).toContain("# Keep my settings");
    expect(fs.existsSync(path.join(home, ".hermes/plugins/knowbase-context"))).toBe(false);
  });

  it("does not recreate integrations in periodic mode or override explicit Hermes disable", () => {
    installed();
    syncAgentConfig(kb, home, { onlyExisting: true });
    expect(fs.existsSync(path.join(home, ".cursor/hooks.json"))).toBe(false);
    expect(fs.existsSync(path.join(home, ".hermes/plugins"))).toBe(false);
    write(path.join(home, ".hermes/config.yaml"), "plugins:\n  disabled: [knowbase-context]\n");
    expect(syncAgentConfig(kb, home).find(c => c.name === "Hermes")?.action).toBe("skipped");
    expect(fs.existsSync(path.join(home, ".hermes/plugins/knowbase-context"))).toBe(false);
  });

  it("isolates broken client configs and never overwrites foreign plugin directories", () => {
    installed();
    const hooks = path.join(home, ".cursor/hooks.json");
    write(hooks, "{broken");
    const changes = syncAgentConfig(kb, home);
    expect(changes.find(c => c.name === "Cursor")?.action).toBe("skipped");
    expect(changes.find(c => c.name === "Hermes")?.action).toBe("created");
    expect(fs.readFileSync(hooks, "utf8")).toBe("{broken");
    uninstallAgentConfig(home);
    write(path.join(home, ".hermes/plugins/knowbase-context/__init__.py"), "personal");
    expect(syncAgentConfig(kb, home).find(c => c.name === "Hermes")?.action).toBe("skipped");
    expect(fs.readFileSync(path.join(home, ".hermes/plugins/knowbase-context/__init__.py"), "utf8")).toBe("personal");
  });

  it("respects removed registration and context in periodic mode", () => {
    installed();
    const changes = syncAgentConfig(kb, home);
    const cursor = changes.find(c => c.name === "Cursor")!;
    expect(cursor).toBeDefined();
    write(path.join(home, ".cursor/hooks.json"), '{"version":1,"hooks":{}}');
    fs.rmSync(cursor.file);
    write(path.join(kb, "new.md"), "New facts");
    syncAgentConfig(kb, home, { onlyExisting: true });
    expect(fs.existsSync(cursor.file)).toBe(false);
    expect(JSON.parse(fs.readFileSync(path.join(home, ".cursor/hooks.json"), "utf8")).hooks).toEqual({});
  });

  it("does not resurrect a deleted Cursor rule during periodic refresh", () => {
    installed();
    syncAgentConfig(kb, home);
    const rule = path.join(home, ".cursor/knowbase/plugin/rules/knowbase.mdc");
    expect(fs.existsSync(rule)).toBe(true);
    fs.rmSync(rule);
    syncAgentConfig(kb, home, { onlyExisting: true });
    expect(fs.existsSync(rule)).toBe(false);
  });

  it.each([
    ["Hermes", ".hermes/plugins/knowbase-context/__init__.py"],
    ["Hermes", ".hermes/plugins/knowbase-context/plugin.yaml"],
    ["Cursor", ".cursor/knowbase/workspace-open.cjs"],
    ["Cursor", ".cursor/knowbase/plugin/.cursor-plugin/plugin.json"],
  ])("does not resurrect a deleted %s runtime artifact: %s", (name, rel) => {
    installed();
    syncAgentConfig(kb, home);
    fs.rmSync(path.join(home, rel));
    expect(additionalAgentConfigStatus(home).find(s => s.name === name)?.state).not.toContain("已配置");
    syncAgentConfig(kb, home, { onlyExisting: true });
    expect(fs.existsSync(path.join(home, rel))).toBe(false);
  });
});
